// SShellClass mirrors the C++ SShell::Class enum (srf/surface.h:420).
// Used during boolean CSG to record, for each side of a trim edge,
// how that side relates to the shell being unioned/subtracted.
type SShellClass uint32

const (
	ShellInside    SShellClass = 100
	ShellOutside   SShellClass = 200
	ShellCoincSame SShellClass = 300
	ShellCoincOpp  SShellClass = 400
)

// shellDotpTol is the dot-product tolerance used by SShell::ClassifyEdge
// (srf/raycast.cpp:16).
const shellDotpTol = 1e-5

// shellClassFromClass bridges the Class enum (the canonical Go enum
// equivalent of the C++ SShell::Class, defined in raycast.go) to the
// SShellClass mirror that pre-dates the full ClassifyEdge port. The two
// enums share semantics; the mirror was introduced when only a partial
// raycast fallback existed.
func shellClassFromClass(c Class) SShellClass {
	switch c {
	case SurfInside:
		return ShellInside
	case SurfOutside:
		return ShellOutside
	case SurfCoincSame:
		return ShellCoincSame
	case SurfCoincOpp:
		return ShellCoincOpp
	}
	return ShellOutside
}

// Boolean-CSG parity: keepRegion decides whether a half-plane region
// should be kept in the output shell for a given boolean op. The
// region is characterized by its classification against the other
// shell (shell) and against the original trim polygon (orig).
//
// Mirrors the static KeepRegion in solvespace/src/srf/boolean.cpp:274.
func keepRegion(t SurfaceCombineAs, opA bool, shell, orig SShellClass) bool {
	if orig != ShellInside {
		return false
	}
	switch t {
	case SurfaceUnion:
		if opA {
			return shell == ShellOutside
		}
		return shell == ShellOutside || shell == ShellCoincSame
	case SurfaceDiff:
		if opA {
			return shell == ShellOutside || shell == ShellCoincOpp
		}
		return shell == ShellInside
	case SurfaceInter:
		if opA {
			return shell == ShellInside
		}
		return shell == ShellInside || shell == ShellCoincSame
	}
	return false
}

// keepEdge decides whether a single trim edge should be kept, based on
// the classifications of the regions on each side. An edge is kept
// exactly when its in-direction is kept but its out-direction is not.
//
// Mirrors the static KeepEdge in solvespace/src/srf/boolean.cpp:310.
func keepEdge(t SurfaceCombineAs, opA bool, indirShell, outdirShell, indirOrig, outdirOrig SShellClass) bool {
	keepIn := keepRegion(t, opA, indirShell, indirOrig)
	keepOut := keepRegion(t, opA, outdirShell, outdirOrig)
	if keepIn && !keepOut {
		return true
	}
	return false
}

// tagByClassifiedEdge translates an SBspUv::Class on the original-trim
// BSP into the (indir, outdir) SShellClass pair to assume for that
// edge. Mirrors TagByClassifiedEdge in boolean.cpp:323.
func tagByClassifiedEdge(bspclass BspUvClass, indir, outdir *SShellClass) {
	switch bspclass {
	case BspUvInside:
		*indir = ShellInside
		*outdir = ShellInside
	case BspUvOutside:
		*indir = ShellOutside
		*outdir = ShellOutside
	case BspUvEdgeParallel:
		*indir = ShellInside
		*outdir = ShellOutside
	case BspUvEdgeAntipar:
		*indir = ShellOutside
		*outdir = ShellInside
	default:
		*indir = ShellOutside
		*outdir = ShellOutside
	}
}

// findChainAvoiding consumes `src` by selecting an edge that doesn't
// share an avoid point, then walks `src` adding every adjoining edge
// to `dest` until no more can be added. Used by MakeCopyTrimAgainst to
// carve `orig`/`inter` into closed chains while skipping "choosing
// points" (junctions where 3+ edges meet, where the orientation is
// ambiguous).
//
// Mirrors SSurface::FindChainAvoiding in boolean.cpp:378. The outer
// loop has an iteration cap to avoid pathological infinite loops when
// the input chain is degenerate (e.g. coincident overlapping edges
// generated by `MakeIntersectionCurvesAgainst` when both shells are
// coincident at every face).
//
// Choosing tolerance note (PORTING.md §"Remaining work" point 1):
// the C++ SPointList::IncrementTagFor / ContainsPoint route through
// Vector::Equals, which is `DistanceTo < 1e-8`. The Go port
// historically used 1e-9, which is tighter than C++; that's fine for
// well-separated junctions, but it breaks the closed-inter case
// where an exactly-closed curve in 3D projects to uv with closure
// noise in the 1e-9..1e-7 band. Loosening the tolerance to 1e-8
// matches the C++ semantics and lets the chain finder close the loop.
func findChainAvoiding(src, dest *SEdgeList, avoid *[]geom.Vector) {
	if len(src.Edges) == 0 {
		return
	}
	const tol = 1e-8
	const maxIters = 1024
	avoidSet := func(p geom.Vector) bool {
		for _, q := range *avoid {
			if p.DistanceTo(q) < tol {
				return true
			}
		}
		return false
	}
	// Take the first edge as the seed.
	dest.Edges = append(dest.Edges, src.Edges[0])
	src.Edges = src.Edges[1:]
	for iter := 0; iter < maxIters; iter++ {
		if len(src.Edges) == 0 {
			break
		}
		added := false
		startPoint := dest.Edges[0].A
		endPoint := dest.Edges[len(dest.Edges)-1].B
		startOkay := !avoidSet(startPoint)
		finishOkay := !avoidSet(endPoint)
		i := 0
		for i < len(src.Edges) {
			// Read everything we need from the candidate edge
			// BEFORE we mutate src.Edges — otherwise the slice
			// shift can leave us reading the wrong edge.
			e := src.Edges[i]
			bMatchesStart := startOkay && e.B.DistanceTo(startPoint) < tol
			aMatchesFinish := finishOkay && e.A.DistanceTo(endPoint) < tol
			switch {
			case bMatchesStart:
				dest.Edges = append([]SEdge{e}, dest.Edges...)
				src.Edges = append(src.Edges[:i], src.Edges[i+1:]...)
				startPoint = e.A
				startOkay = !avoidSet(startPoint)
				added = true
			case aMatchesFinish:
				dest.Edges = append(dest.Edges, e)
				src.Edges = append(src.Edges[:i], src.Edges[i+1:]...)
				endPoint = e.B
				finishOkay = !avoidSet(endPoint)
				added = true
			default:
				i++
			}
		}
		if !added {
			break
		}
	}
}

// trimFromEdgeList rebuilds srf's trims from el, merging adjoining
// edges from the same curve (and direction) into one STrimBy with xyz
// start and finish points. Mirrors C++ SSurface::TrimFromEdgeList.
func (srf *SSurface) trimFromEdgeList(el *SEdgeList, asUv bool) {
	for i := range el.Edges {
		el.Edges[i].Tag = 0
	}

	for {
		// Find an edge, any edge; we'll start from there.
		var se *SEdge
		for i := range el.Edges {
			if el.Edges[i].Tag == 0 {
				se = &el.Edges[i]
				break
			}
		}
		if se == nil {
			break
		}
		se.Tag = 1
		stb := STrimBy{
			StartP:    se.A,
			FinishP:   se.B,
			Curve:     core.HSCurve{V: uint32(se.AuxA)},
			Backwards: se.AuxB != 0,
		}

		// Find adjoining edges from the same curve; those should be
		// merged into a single trim.
		for {
			merged := false
			for i := range el.Edges {
				se := &el.Edges[i]
				if se.Tag != 0 {
					continue
				}
				if se.AuxA != int(stb.Curve.V) {
					continue
				}
				if (se.AuxB != 0) != stb.Backwards {
					continue
				}

				if se.A.Equals(stb.FinishP) {
					stb.FinishP = se.B
					se.Tag = 1
					merged = true
				} else if se.B.Equals(stb.StartP) {
					stb.StartP = se.A
					se.Tag = 1
					merged = true
				}
			}
			if !merged {
				break
			}
		}

		if asUv {
			stb.StartP = srf.PointAt(stb.StartP.X, stb.StartP.Y)
			stb.FinishP = srf.PointAt(stb.FinishP.X, stb.FinishP.Y)
		}

		// And add the merged trim, with xyz (not uv like the polygon) pts
		srf.Trim = append(srf.Trim, stb)
	}
}

// The C++ MakeCopyTrimAgainst rewrites each STrimBy's Curve handle
// to refer to the new (split) curve in `into`. That rewrite is done
// up-front in `SShell::CopyCurvesSplitAgainst`, which records the
// parent curve's newH (the handle in `into`). The Go port defers
// that rewrite to the final SShell::RewriteSurfaceHandlesForCurves
// pass at the end of MakeFromBoolean, so the STrimBy entries we
// build here keep their parent-relative Curve ids. The trim from
// `makeSurfaceEdgesIntoUv` below is therefore built directly from the
// curve in `into` that the trim refers to (looked up by raw H value).
//
// An earlier version of this file also called a second helper
// (`makeEdgesIntoForBoolean`) after `makeSurfaceEdgesIntoUv` to
// rebuild `orig` a second time from every curve in `into` touching
// `srf.H`, without clearing the edge list first. That appended a
// second, overlapping copy of the boundary AND pulled in every
// CurveSourceIntersection curve touching this surface (which
// belongs in the separate `inter` list built below, not `orig`) —
// neither matches the C++, which builds `orig` from `ret.trim`
// alone (`boolean.cpp:528`: `ret.MakeEdgesInto(into, &orig,
// MakeAs::UV)`). That second call has been removed;
// `makeSurfaceEdgesIntoUv` alone now mirrors the C++.

// edgeNormalsWithinSurface returns a point on the uv edge auv->buv
// (refined onto the curve auxA it approximates) and the edge's inner
// and outer normals within srf, in xyz; surfN gets srf's normal there.
// Mirrors C++ SSurface::EdgeNormalsWithinSurface (boolean.cpp).
func (srf *SSurface) edgeNormalsWithinSurface(auv, buv geom.Point2d, shell, sha, shb *SShell,
	auxA int, surfN *geom.Vector) (pt, enin, enout geom.Vector) {
	// the midpoint of the edge
	muv := auv.Plus(buv).ScaledBy(0.5)

	pt = srf.PointAtUv(muv)

	// If this edge just approximates a curve, then refine our midpoint so
	// so that it actually lies on that curve too. Otherwise stuff like
	// point-on-face tests will fail, since the point won't actually lie
	// on the other face.
	if sc := shell.FindCurve(core.HSCurve{V: uint32(auxA)}); sc != nil {
		if sc.IsExact && sc.Exact.Degree != 1 {
			t, _ := sc.Exact.ClosestPointTo(pt, false)
			pt = sc.Exact.PointAt(t)
		} else if !sc.IsExact {
			trimmedA := sc.GetSurfaceA(sha, shb)
			trimmedB := sc.GetSurfaceB(sha, shb)
			if trimmedA != nil && trimmedB != nil {
				pt = trimmedA.ClosestPointOnThisAndSurface(trimmedB, pt)
			}
		}
	}
	srf.ClosestPointTo(pt, &muv, true)

	*surfN = srf.NormalAt(muv.U, muv.V)

	// Compute the edge's inner normal in xyz space. Use the configured
	// chord tolerance as the probe distance, but never more than a
	// fraction of this edge's own length: the classification must probe
	// the surfaces close to the edge, and a coarse tolerance on a small
	// model would otherwise evaluate them far away, or even extrapolate
	// them outside their domain, and misclassify.
	ab := srf.PointAtUv(auv).Minus(srf.PointAtUv(buv))
	enxyz := ab.Cross(*surfN).WithMagnitude(math.Min(ChordTolMm(), ab.Magnitude()/10))
	// And based on that, compute the edge's inner normal in uv space. This
	// vector is perpendicular to the edge in xyz, but not necessarily in uv.
	var tu, tv geom.Vector
	srf.TangentsAt(muv.U, muv.V, &tu, &tv, true)
	n := tu.Cross(tv)
	// since tu and tv may not be orthogonal, use y in place of v, x in place of u.
	// |y| = |v|sin(theta) where theta is the angle between tu and tv.
	ty := n.Cross(tu).ScaledBy(1.0 / tu.MagSquared())
	tx := tv.Cross(n).ScaledBy(1.0 / tv.MagSquared())

	enuv := geom.Point2d{
		U: enxyz.Dot(tx) / tx.MagSquared(),
		V: enxyz.Dot(ty) / ty.MagSquared(),
	}

	// Compute the inner and outer normals of this edge (within the srf),
	// in xyz space. These are not necessarily antiparallel, if the
	// surface is curved.
	pin := srf.PointAtUv(muv.Minus(enuv))
	pout := srf.PointAtUv(muv.Plus(enuv))
	enin = pin.Minus(pt)
	enout = pout.Minus(pt)
	return
}

// classifyEdge returns the (indir, outdir) SShellClass pair for the
// edge ea→eb, where p is a representative midpoint on the surface
// and edge_n_in / edge_n_out are the half-plane normal probe
// directions. Mirrors SShell::ClassifyEdge in raycast.cpp:463.
//
// Result: returns true if classification succeeded and writes
// shell classification into *indir and *outdir.
func (s *SShell) classifyEdge(indir, outdir *SShellClass,
	ea, eb, p, edgeNIn, edgeNOut, surfN geom.Vector) bool {
	var inDir, outDir Class
	if !s.ClassifyEdge(&inDir, &outDir, ea, eb, p, edgeNIn, edgeNOut, surfN) {
		return false
	}
	*indir = shellClassFromClass(inDir)
	*outdir = shellClassFromClass(outDir)
	return true
}

// makeCopyTrimAgainst is the per-surface counterpart of
// SShell::MakeFromBoolean. For a single surface from `parent`, it
// produces a trimmed copy whose boundary includes both the parent's
// (split) trim curves and the new intersection curves computed
// against `agnst`. The resulting surface is appended to `into`,
// along with its STrimBy list. Each region of the surface is then
// classified against `agnst`; only the regions appropriate for the
// boolean op (UNION / DIFFERENCE / INTERSECTION) are kept.
//
// Mirrors SSurface::MakeCopyTrimAgainst in boolean.cpp:497. This is a
// focused Go port that prioritises the boolean-csg parity for the
// planar / coplanar / cylindrical fixture cases over the C++'s full
// edge-on-edge / tangent-face handling.
func (srf *SSurface) makeCopyTrimAgainst(parent, sha, shb, into *SShell,
	t SurfaceCombineAs, dbgIndex int) SSurface {
	if parent == nil || sha == nil || shb == nil || into == nil {
		return *srf
	}
	opA := parent == sha
	var agnst *SShell
	if opA {
		agnst = shb
	} else {
		agnst = sha
	}
	ret := *srf
	ret.Trim = nil
	ret.TrimBuilt = true

	// Step 1 (C++ line 511-518): rewrite trim curves to use the
	// new (split) curve handles. CopyCurvesSplitAgainst stored the
	// parent-relative curve's NewH (the handle in `into` of the
	// first emitted segment). Look up each trim curve in the parent
	// shell and use that NewH as the rewritten handle.
	for i := range srf.Trim {
		stb := srf.Trim[i]
		if pc := parent.FindCurve(stb.Curve); pc != nil {
			stb.Curve = pc.NewH
		}
		ret.Trim = append(ret.Trim, stb)
	}

	// Step 2 (C++ line 520-523): the second operand of DIFFERENCE
	// gets reversed.
	if t == SurfaceDiff && !opA {
		ret.Reverse()
	}

	// Step 3 (C++ line 528-532): build the orig trim polygon from
	// the new (split) curves.
	orig := &SEdgeList{}
	ret.MakeEdgesInto(into, orig, true, nil)
	ret.Trim = nil
	origBsp := SBspUvFrom(orig, &ret)

	// Step 4 (C++ line 535-594): build the inter edge list from the
	// intersection curves in `into`.
	inter := &SEdgeList{}
	for i := range into.Curve {
		ic := &into.Curve[i]
		if ic.Source != CurveSourceIntersection {
			continue
		}
		var ss *SSurface
		if opA {
			if ic.SurfA != srf.H {
				continue
			}
			ss = shb.FindSurface(ic.SurfB)
		} else {
			if ic.SurfB != srf.H {
				continue
			}
			ss = sha.FindSurface(ic.SurfA)
		}
		if ss == nil {
			continue
		}
		for k := 1; k < len(ic.Points); k++ {
			a := ic.Points[k-1].P
			b := ic.Points[k].P

			var auv, buv geom.Point2d
			ss.ClosestPointTo(a, &auv, true)
			ss.ClosestPointTo(b, &buv, true)

			c := BspUvOutside
			if ss.Bsp != nil {
				c = ss.Bsp.ClassifyEdge(auv, buv, ss)
			}
			if c == BspUvOutside {
				continue
			}
			var tap, tbp geom.Point2d
			ret.ClosestPointTo(a, &tap, true)
			ret.ClosestPointTo(b, &tbp, true)
			ta := geom.Vector{X: tap.U, Y: tap.V}
			tb := geom.Vector{X: tbp.U, Y: tbp.V}

			tn := ret.NormalAt(tap.U, tap.V)
			sn := ss.NormalAt(auv.U, auv.V)

			// We are subtracting the portion of our surface that
			// lies in the shell, so the in-plane edge normal should
			// point opposite to the surface normal.
			tnxd := tn.Cross(b.Minus(a))
			dot := tnxd.Dot(sn)
			if mathAbs(dot) < shellDotpTol*tnxd.Magnitude()*sn.Magnitude() {
				// The surfaces are tangent along this curve, so their
				// normals give no orientation for it. Add the edge in
				// both directions; the classification against the
				// shells keeps the correctly oriented one and
				// discards the other.
				inter.AddEdge(ta, tb, int(ic.H.V), 0, 0)
				inter.AddEdge(tb, ta, int(ic.H.V), 1, 0)
				continue
			}
			bkwds := true
			if dot < 0 {
				bkwds = !bkwds
			}
			if (t == SurfaceDiff && !opA) || t == SurfaceInter {
				// Invert all newly created edges for intersection
				bkwds = !bkwds
			}
			if bkwds {
				inter.AddEdge(tb, ta, int(ic.H.V), 1, 0)
			} else {
				inter.AddEdge(ta, tb, int(ic.H.V), 0, 0)
			}
		}
	}

	// Step 5 (C++ line 596-618): build the list of "choosing points"
	// — junctions where more than 2 edges meet. Edges meeting at a
	// non-choosing point must either all be kept or all be discarded
	// (otherwise the trim polygon would be open).
	//
	// Mirrors the C++ SPointList::IncrementTagFor + tag==2 cleanup:
	// for every endpoint of every edge, increment a counter; then
	// remove entries with count != 2. The result is a list of points
	// where 3+ edges meet, which the chain-finding code uses to
	// avoid splitting chains at junction points.
	choosing := []geom.Vector{}
	chooseTag := make(map[geom.Vector]int)
	// PORTING.md §"Remaining work" point 1: match C++'s 1e-8
	// bucket tolerance (the Go port historically used the tighter
	// 1e-9, which broke the closed-inter case when closure noise
	// landed in the 1e-9..1e-7 band).
	const chooseTol = 1e-8
	incChoose := func(p geom.Vector) {
		for k := range chooseTag {
			if k.DistanceTo(p) < chooseTol {
				chooseTag[k]++
				return
			}
		}
		chooseTag[p] = 1
	}
	for i := range orig.Edges {
		incChoose(orig.Edges[i].A)
		incChoose(orig.Edges[i].B)
	}
	for i := range inter.Edges {
		incChoose(inter.Edges[i].A)
		incChoose(inter.Edges[i].B)
	}
	for k, v := range chooseTag {
		if v != 2 {
			choosing = append(choosing, k)
		}
	}

	// Step 6 (C++ line 623-661): walk orig chains, classify, keep.
	final := &SEdgeList{}
	for len(orig.Edges) > 0 {
		chain := &SEdgeList{}
		findChainAvoiding(orig, chain, &choosing)
		if len(chain.Edges) == 0 {
			break
		}
		midIdx := len(chain.Edges) / 2
		if midIdx >= len(chain.Edges) {
			midIdx = len(chain.Edges) - 1
		}
		se := &chain.Edges[midIdx]
		auv := geom.Point2d{U: se.A.X, V: se.A.Y}
		buv := geom.Point2d{U: se.B.X, V: se.B.Y}
		var surfN, pt, enin, enout geom.Vector
		pt, enin, enout = ret.edgeNormalsWithinSurface(auv, buv, into, sha, shb, se.AuxA, &surfN)
		var indirShell, outdirShell SShellClass = ShellOutside, ShellOutside
		agnst.classifyEdge(&indirShell, &outdirShell,
			ret.PointAtUv(auv), ret.PointAtUv(buv),
			pt, enin, enout, surfN)
		keep := keepEdge(t, opA,
			indirShell, outdirShell,
			ShellInside, ShellOutside)
		if keep {
			for _, e := range chain.Edges {
				final.AddEdge(e.A, e.B, e.AuxA, e.AuxB, 0)
			}
		}
		chain.Edges = nil
	}

	// Step 7 (C++ line 663-720): walk inter chains, classify, keep.
	for len(inter.Edges) > 0 {
		chain := &SEdgeList{}
		findChainAvoiding(inter, chain, &choosing)
		if len(chain.Edges) == 0 {
			break
		}
		midIdx := len(chain.Edges) / 2
		if midIdx >= len(chain.Edges) {
			midIdx = len(chain.Edges) - 1
		}
		se := &chain.Edges[midIdx]
		auv := geom.Point2d{U: se.A.X, V: se.A.Y}
		buv := geom.Point2d{U: se.B.X, V: se.B.Y}
		var surfN, pt, enin, enout geom.Vector
		pt, enin, enout = ret.edgeNormalsWithinSurface(auv, buv, into, sha, shb, se.AuxA, &surfN)
		var indirShell, outdirShell SShellClass = ShellOutside, ShellOutside
		var indirOrig, outdirOrig SShellClass = ShellInside, ShellOutside
		var cThis BspUvClass = BspUvOutside
		if origBsp != nil {
			cThis = origBsp.ClassifyEdge(auv, buv, &ret)
		}
		if cThis == BspUvEdgeParallel {
			chain.Edges = nil
			continue
		}
		tagByClassifiedEdge(cThis, &indirOrig, &outdirOrig)
		agnst.classifyEdge(&indirShell, &outdirShell,
			ret.PointAtUv(auv), ret.PointAtUv(buv),
			pt, enin, enout, surfN)
		keep := keepEdge(t, opA,
			indirShell, outdirShell,
			indirOrig, outdirOrig)
		if keep {
			for _, e := range chain.Edges {
				final.AddEdge(e.A, e.B, e.AuxA, e.AuxB, 0)
			}
		}
		chain.Edges = nil
	}

	// Step 8 (C++ line 723-727): cull duplicate / anti-parallel edges.
	final.CullExtraneousEdges(true)

	// Step 9 (C++ line 729-744): assemble the trim polygon from the
	// kept edges; mark booleanFailed in `into` if it fails to close.
	ret.trimFromEdgeList(final, true)
	var poly SPolygon
	final.lClearTags()
	if !final.AssemblePolygon(&poly, nil, true) {
		into.BooleanFailed = true
	}

	return ret
}

// lClearTags is a small helper to reset the Tag field on every edge
// in el (used after the inter/orig chain extraction above).
func (el *SEdgeList) lClearTags() {
	for i := range el.Edges {
		el.Edges[i].Tag = 0
	}
}

// copySurfacesTrimAgainstAccurate replaces CopySurvesTrimAgainst
// with the proper per-surface MakeCopyTrimAgainst pipeline. For each
// surface in `receiver`, it produces a trimmed copy whose boundary
// includes both the receiver's (split) trim curves and the new
// intersection curves computed against `sha` and `shb`. The
// resulting surfaces are appended to `into`.
func copySurfacesTrimAgainstAccurate(receiver, sha, shb, into *SShell, t SurfaceCombineAs) {
	if receiver == nil || sha == nil || shb == nil || into == nil {
		return
	}
	for i := range receiver.Surface {
		srf := &receiver.Surface[i]
		trimmed := srf.makeCopyTrimAgainst(receiver, sha, shb, into, t, i)
		trimmed.NewH = core.HSSurface{V: uint32(len(into.Surface) + 1)}
		trimmed.H = trimmed.NewH
		into.Surface = append(into.Surface, trimmed)
	}
}
