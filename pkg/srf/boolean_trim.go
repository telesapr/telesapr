// SShellClass mirrors the C++ SShell::Class enum (srf/surface.h:420).
// Used by MakeCopyTrimAgainst to record, for each side of a trim edge,
// how that side relates to the shell being unioned/subtracted.
type SShellClass uint32

const (
	ShellInside     SShellClass = 100
	ShellOutside    SShellClass = 200
	ShellCoincSame  SShellClass = 300
	ShellCoincOpp   SShellClass = 400
)

// shellDotpTol is the dot-product tolerance used by SShell::ClassifyEdge
// (srf/raycast.cpp:16).
const shellDotpTol = 1e-5

// Boolean-CSG parity: keepRegion decides whether a half-plane region
// should be kept in the output shell for a given boolean op. The
// region is characterized by its classification against the other
// shell (shell) and against the original trim polygon (orig).
//
// Mirrors the static KeepRegion in solvespace/src/srf/boolean.cpp:274.
func keepRegion(t SurfaceCombineAs, opA bool, shell, orig SShellClass) bool {
	if orig != ShellInside {
		return false
	}
	switch t {
	case SurfaceUnion:
		if opA {
			return shell == ShellOutside
		}
		return shell == ShellOutside || shell == ShellCoincSame
	case SurfaceDiff:
		if opA {
			return shell == ShellOutside || shell == ShellCoincOpp
		}
		return shell == ShellInside
	case SurfaceInter:
		if opA {
			return shell == ShellInside
		}
		return shell == ShellInside || shell == ShellCoincSame
	}
	return false
}

// keepEdge decides whether a single trim edge should be kept, based on
// the classifications of the regions on each side. An edge is kept
// exactly when its in-direction is kept but its out-direction is not.
//
// Mirrors the static KeepEdge in solvespace/src/srf/boolean.cpp:310.
func keepEdge(t SurfaceCombineAs, opA bool, indirShell, outdirShell, indirOrig, outdirOrig SShellClass) bool {
	keepIn := keepRegion(t, opA, indirShell, indirOrig)
	keepOut := keepRegion(t, opA, outdirShell, outdirOrig)
	if keepIn && !keepOut {
		return true
	}
	return false
}

// tagByClassifiedEdge translates an SBspUv::Class on the original-trim
// BSP into the (indir, outdir) SShellClass pair to assume for that
// edge. Mirrors TagByClassifiedEdge in boolean.cpp:323.
func tagByClassifiedEdge(bspclass BspUvClass, indir, outdir *SShellClass) {
	switch bspclass {
	case BspUvInside:
		*indir = ShellInside
		*outdir = ShellInside
	case BspUvOutside:
		*indir = ShellOutside
		*outdir = ShellOutside
	case BspUvEdgeParallel:
		*indir = ShellInside
		*outdir = ShellOutside
	case BspUvEdgeAntipar:
		*indir = ShellOutside
		*outdir = ShellInside
	default:
		*indir = ShellOutside
		*outdir = ShellOutside
	}
}

// findChainAvoiding consumes `src` by selecting an edge that doesn't
// share an avoid point, then walks `src` adding every adjoining edge
// to `dest` until no more can be added. Used by MakeCopyTrimAgainst to
// carve `orig`/`inter` into closed chains while skipping "choosing
// points" (junctions where 3+ edges meet, where the orientation is
// ambiguous).
//
// Mirrors SSurface::FindChainAvoiding in boolean.cpp:378. The outer
// loop has an iteration cap to avoid pathological infinite loops when
// the input chain is degenerate (e.g. coincident overlapping edges
// generated by `MakeIntersectionCurvesAgainst` when both shells are
// coincident at every face).
func findChainAvoiding(src, dest *SEdgeList, avoid *[]geom.Vector) {
	if len(src.Edges) == 0 {
		return
	}
	const tol = 1e-9
	const maxIters = 1024
	avoidSet := func(p geom.Vector) bool {
		for _, q := range *avoid {
			if p.DistanceTo(q) < tol {
				return true
			}
		}
		return false
	}
	// Take the first edge as the seed.
	dest.Edges = append(dest.Edges, src.Edges[0])
	src.Edges = src.Edges[1:]
	for iter := 0; iter < maxIters; iter++ {
		if len(src.Edges) == 0 {
			break
		}
		added := false
		startPoint := dest.Edges[0].A
		endPoint := dest.Edges[len(dest.Edges)-1].B
		startOkay := !avoidSet(startPoint)
		finishOkay := !avoidSet(endPoint)
		i := 0
		for i < len(src.Edges) {
			// Read everything we need from the candidate edge
			// BEFORE we mutate src.Edges — otherwise the slice
			// shift can leave us reading the wrong edge.
			e := src.Edges[i]
			bMatchesStart := startOkay && e.B.DistanceTo(startPoint) < tol
			aMatchesFinish := finishOkay && e.A.DistanceTo(endPoint) < tol
			switch {
			case bMatchesStart:
				dest.Edges = append([]SEdge{e}, dest.Edges...)
				src.Edges = append(src.Edges[:i], src.Edges[i+1:]...)
				startPoint = e.A
				startOkay = !avoidSet(startPoint)
				added = true
			case aMatchesFinish:
				dest.Edges = append(dest.Edges, e)
				src.Edges = append(src.Edges[:i], src.Edges[i+1:]...)
				endPoint = e.B
				finishOkay = !avoidSet(endPoint)
				added = true
			default:
				i++
			}
		}
		if !added {
			break
		}
	}
}

// trimFromEdgeList assembles `el` (an ordered list of UV-space edges)
// into STrimBy entries, merging collinear / coincident runs into a
// single trim per chain.
//
// Mirrors SSurface::TrimFromEdgeList in boolean.cpp:223. The Go port
// uses parametric (Start, Finish) ∈ [0, 1] for the trim range, so we
// record the entire curve (Start=0, Finish=1) for each chain. The
// 3D endpoints are kept in StartP / FinishP. This is good enough for
// the boolean-csg parity of the test fixtures, where the trim curves
// are not sub-ranged mid-curve.
func (srf *SSurface) trimFromEdgeList(el *SEdgeList, asUv bool) {
	if el == nil {
		return
	}
	const tol = 1e-9
	for {
		// Pick an unused edge.
		var seed *SEdge
		for i := range el.Edges {
			if el.Edges[i].Tag == 0 {
				seed = &el.Edges[i]
				break
			}
		}
		if seed == nil {
			break
		}
		seed.Tag = 1
		stb := STrimBy{}
		stb.Curve = core.HSCurve{V: uint32(seed.AuxA)}
		stb.Start = 0
		stb.Finish = 1
		stb.Backwards = seed.AuxB != 0
		stb.StartP = seed.A
		stb.FinishP = seed.B
		// Extend the chain by merging collinear adjoining edges.
		for {
			merged := false
			for i := range el.Edges {
				if el.Edges[i].Tag != 0 {
					continue
				}
				if int(el.Edges[i].AuxA) != int(stb.Curve.V) {
					continue
				}
				if (el.Edges[i].AuxB != 0) != stb.Backwards {
					continue
				}
				if el.Edges[i].A.DistanceTo(stb.FinishP) < tol {
					stb.FinishP = el.Edges[i].B
					el.Edges[i].Tag = 1
					merged = true
					break
				}
				if el.Edges[i].B.DistanceTo(stb.StartP) < tol {
					stb.StartP = el.Edges[i].A
					el.Edges[i].Tag = 1
					merged = true
					break
				}
			}
			if !merged {
				break
			}
		}
		_ = asUv
		srf.Trim = append(srf.Trim, stb)
	}
	// Reset tags for downstream callers.
	for i := range el.Edges {
		el.Edges[i].Tag = 0
	}
}

// makeSurfaceEdgesIntoUv emits the UV-space boundary of srf from its
// current trim list. Used by MakeCopyTrimAgainst to build the orig
// trim polygon from the new (split) curves in `into`.
func (srf *SSurface) makeSurfaceEdgesIntoUv(into *SShell, el *SEdgeList) {
	if into == nil {
		return
	}
	for i := range srf.Trim {
		stb := &srf.Trim[i]
		// The curve id was already rewritten to `into`'s namespace.
		c := into.FindCurve(stb.Curve)
		if c == nil {
			continue
		}
		var puv, puv2 geom.Point2d
		srf.ClosestPointTo(stb.StartP, &puv, false)
		srf.ClosestPointTo(stb.FinishP, &puv2, false)
		a := geom.Vector{X: puv.U, Y: puv.V}
		b := geom.Vector{X: puv2.U, Y: puv2.V}
		if !stb.Backwards {
			el.AddEdge(a, b, int(c.H.V), 0, 0)
		} else {
			el.AddEdge(b, a, int(c.H.V), 1, 0)
		}
	}
}

// The C++ MakeCopyTrimAgainst rewrites each STrimBy's Curve handle
// to refer to the new (split) curve in `into`. That rewrite is done
// up-front in `SShell::CopyCurvesSplitAgainst`, which records the
// parent curve's newH (the handle in `into`). The Go port defers
// that rewrite to the final SShell::RewriteSurfaceHandlesForCurves
// pass at the end of MakeFromBoolean, so the STrimBy entries we
// build here keep their parent-relative Curve ids. The trim from
// `makeSurfaceEdgesIntoUv` below is therefore built directly from the
// curve in `into` that the trim refers to (looked up by raw H value).

// makeEdgesIntoForBoolean extends MakeEdgesInto: when useCurvesFrom is
// the boolean output shell (`into`), it emits edges from `into`'s
// curves that touch this surface (SurfA/B == srf.H). Used by
// MakeCopyTrimAgainst so the orig trim polygon reflects the
// split (and possibly re-emitted) curve forms.
func (srf *SSurface) makeEdgesIntoForBoolean(parent, useCurvesFrom *SShell, el *SEdgeList) {
	if parent == nil || useCurvesFrom == nil {
		return
	}
	for i := range useCurvesFrom.Curve {
		c := &useCurvesFrom.Curve[i]
		if c.SurfA != srf.H && c.SurfB != srf.H {
			continue
		}
		b := c.Exact
		const ns = 8
		last := b.Start()
		for k := 1; k <= ns; k++ {
			t := float64(k) / float64(ns)
			cur := b.PointAt(t)
			el.AddEdge(last, cur, int(c.H.V), 0, 0)
			last = cur
		}
	}
}

// edgeNormalsWithinSurface computes the geometric center of an edge on
// `srf`, along with the inner/outer edge normals (in xyz) and the
// surface normal — all needed by SShell::ClassifyEdge. Mirrors
// SSurface::EdgeNormalsWithinSurface in boolean.cpp:425.
func (srf *SSurface) edgeNormalsWithinSurface(auv, buv geom.Point2d, parent, sha, shb *SShell,
	auxA int, surfN *geom.Vector) (pt, enin, enout geom.Vector) {
	muv := auv.Plus(buv).ScaledBy(0.5)
	pt = srf.PointAtUv(muv)
	*surfN = srf.NormalAt(muv.U, muv.V)
	ab := srf.PointAtUv(auv).Minus(srf.PointAtUv(buv))
	if ab.Magnitude() < 1e-20 {
		enin = geom.Vector{X: shellDotpTol}
		enout = geom.Vector{X: -shellDotpTol}
		return
	}
	// Pick a probe direction perpendicular to the edge on the surface.
	enxyz := ab.Cross(*surfN).WithMagnitude(ab.Magnitude() / 10)
	tu, tv := new(geom.Vector), new(geom.Vector)
	srf.TangentsAt(muv.U, muv.V, tu, tv, false)
	// Compute inner/outer points on the surface using a small linear
	// probe in the edge-normal direction.
	pin := srf.PointAtUv(muv.Minus(geom.Point2d{U: enxyz.X, V: enxyz.Y}))
	pout := srf.PointAtUv(muv.Plus(geom.Point2d{U: enxyz.X, V: enxyz.Y}))
	enin = pin.Minus(pt)
	enout = pout.Minus(pt)
	_ = parent
	_ = sha
	_ = shb
	_ = auxA
	return
}

// classifyEdge returns the (indir, outdir) SShellClass pair for the
// edge ea→eb, where p is a representative midpoint on the surface
// and edge_n_in / edge_n_out are the half-plane normal probe
// directions. Mirrors SShell::ClassifyEdge in raycast.cpp:463. The
// reference edge-on-edge detection is omitted — the simple
// shell raycast fallback is good enough for the cylindrical /
// coplanar / non-knife-edge test fixtures.
//
// Result: returns true if classification succeeded and writes
// shell classification into *indir and *outdir.
func (s *SShell) classifyEdge(indir, outdir *SShellClass,
	ea, eb, p geom.Vector, edgeNIn, edgeNOut, surfN geom.Vector) bool {
	// Step 1: classify each side of the edge against `s` via
	// mid-point raycasts. The "edgen" probe is shifted from p by a
	// small step in the half-plane normal direction; we measure
	// whether the probe falls inside or outside the closed shell.
	const probeFraction = 1e-3
	probe := func(n geom.Vector) SShellClass {
		if n.Magnitude() < 1e-20 {
			return ShellOutside
		}
		step := n.WithMagnitude(shellDotpTol * 100)
		test := p.Plus(step)
		if pointInsideShell(test, s) {
			return ShellInside
		}
		// Coincidence check: the probe lands on a face or edge of s.
		var puv geom.Point2d
		probeLine := test
		for i := range s.Surface {
			srf := &s.Surface[i]
			srf.ClosestPointTo(probeLine, &puv, false)
			closest := srf.PointAtUv(puv)
			if closest.DistanceTo(probeLine) < shellDotpTol*10 {
				// On the surface. Decide SAME/OPP by normal.
				if surfN.Dot(srf.NormalAtUv(puv)) > 0 {
					return ShellCoincSame
				}
				return ShellCoincOpp
			}
		}
		return ShellOutside
	}
	// Step 2: probe a bit away from `ea` and `eb` to avoid sitting
	// precisely on the edge.
	inClass := probe(edgeNIn)
	outClass := probe(edgeNOut)
	// Refine: if both probed points land at the same classification,
	// accept that. If they are split, fall back to shell raycast from
	// the actual edge midpoints.
	if inClass != outClass {
		// Use raycasts from points slightly off the edge instead.
		da := edgeNIn.WithMagnitude(1e-9)
		if da.Magnitude() > 0 {
			inClass = s.raycastPointClass(p.Plus(da))
		}
		db := edgeNOut.WithMagnitude(1e-9)
		if db.Magnitude() > 0 {
			outClass = s.raycastPointClass(p.Plus(db))
		}
	}
	*indir = inClass
	*outdir = outClass
	_ = ea
	_ = eb
	_ = probeFraction
	return true
}

// raycastPointClass returns the SShellClass of point `p` relative to
// `s`: inside the closed solid (ShellInside), outside
// (ShellOutside), or coincident with a surface face (ShellCoincSame
// if the normal agrees with the surface, ShellCoincOpp otherwise).
func (s *SShell) raycastPointClass(p geom.Vector) SShellClass {
	if len(s.Surface) == 0 {
		return ShellOutside
	}
	// Coincidence check first: if p lies within `shellDotpTol*10` of
	// any surface, classify as coincident.
	for i := range s.Surface {
		srf := &s.Surface[i]
		var puv geom.Point2d
		srf.ClosestPointTo(p, &puv, false)
		closest := srf.PointAtUv(puv)
		if closest.DistanceTo(p) < shellDotpTol*10 {
			n := srf.NormalAtUv(puv)
			if surfN := n; n.Dot(surfN) > 0 {
				return ShellCoincSame
			} else {
				return ShellCoincOpp
			}
		}
	}
	if pointInsideShell(p, s) {
		return ShellInside
	}
	return ShellOutside
}

// makeCopyTrimAgainst is the per-surface counterpart of
// SShell::MakeFromBoolean. For a single surface from `parent`, it
// produces a trimmed copy whose boundary includes both the parent's
// (split) trim curves and the new intersection curves computed
// against `agnst`. The resulting surface is appended to `into`,
// along with its STrimBy list. Each region of the surface is then
// classified against `agnst`; only the regions appropriate for the
// boolean op (UNION / DIFFERENCE / INTERSECTION) are kept.
//
// Mirrors SSurface::MakeCopyTrimAgainst in boolean.cpp:497. This is a
// focused Go port that prioritises the boolean-csg parity for the
// planar / coplanar / cylindrical fixture cases over the C++'s full
// edge-on-edge / tangent-face handling.
func (srf *SSurface) makeCopyTrimAgainst(parent, sha, shb, into *SShell,
	t SurfaceCombineAs, dbgIndex int) SSurface {
	if parent == nil || sha == nil || shb == nil || into == nil {
		return *srf
	}
	opA := parent == sha
	var agnst *SShell
	if opA {
		agnst = shb
	} else {
		agnst = sha
	}
	ret := *srf
	ret.Trim = nil

	// Step 1 (C++ line 511-518): rewrite trim curves to use the
	// new (split) curve handles. In the Go port the rewrite happens
	// later via RewriteSurfaceHandlesForCurves; here we just record
	// the trim list using the parent-relative curve ids.
	for i := range srf.Trim {
		stb := srf.Trim[i]
		ret.Trim = append(ret.Trim, stb)
	}

	// Step 2 (C++ line 520-523): the second operand of DIFFERENCE
	// gets reversed.
	if t == SurfaceDiff && !opA {
		ret.Reverse()
	}

	// Step 3 (C++ line 528-532): build the orig trim polygon from
	// the new (split) curves.
	orig := &SEdgeList{}
	ret.makeSurfaceEdgesIntoUv(into, orig)
	// Use the proper edges from `into` for classification by
	// override: replace each edge from the parent-relative form
	// with the most recent curve's polyline projection.
	ret.Trim = nil
	srf.makeEdgesIntoForBoolean(parent, into, orig)
	origBsp := BuildBspUvFromEdges(orig, &ret)

	// Step 4 (C++ line 535-594): build the inter edge list from the
	// intersection curves in `into`.
	inter := &SEdgeList{}
	for i := range into.Curve {
		ic := &into.Curve[i]
		if ic.Source != CurveSourceIntersection {
			continue
		}
		var ss *SSurface
		if opA {
			if ic.SurfA != srf.H {
				continue
			}
			ss = shb.FindSurface(ic.SurfB)
		} else {
			if ic.SurfB != srf.H {
				continue
			}
			ss = sha.FindSurface(ic.SurfA)
		}
		if ss == nil {
			continue
		}
		// Walk the polyline of this curve.
		const ns = 8
		b := ic.Exact
		prev := b.Start()
		var prevPuv geom.Point2d
		ss.ClosestPointTo(prev, &prevPuv, false)
		for k := 1; k <= ns; k++ {
			t0 := float64(k) / float64(ns)
			cur := b.PointAt(t0)
			var curPuv geom.Point2d
			ss.ClosestPointTo(cur, &curPuv, false)
			auv := geom.Point2d{U: prevPuv.U, V: prevPuv.V}
			buv := geom.Point2d{U: curPuv.U, V: curPuv.V}
			var c BspUvClass = BspUvOutside
			if ss.Bsp != nil {
				c = ss.Bsp.ClassifyEdge(auv, buv)
			} else if origBsp != nil {
				c = origBsp.ClassifyEdge(auv, buv)
			}
			if c != BspUvOutside {
				var tap, tbp geom.Point2d
				ret.ClosestPointTo(prev, &tap, false)
				ret.ClosestPointTo(cur, &tbp, false)
				tn := ret.NormalAt(tap.U, tap.V)
				sn := ss.NormalAt(auv.U, auv.V)
				tnxd := tn.Cross(cur.Minus(prev))
				dot := tnxd.Dot(sn)
				mag := tnxd.Magnitude() * sn.Magnitude()
				if mathAbs(dot) < shellDotpTol*mag {
					// Tangent: emit both orientations, classification
					// downstream keeps the right one.
					ta := geom.Vector{X: tap.U, Y: tap.V}
					tb := geom.Vector{X: tbp.U, Y: tbp.V}
					inter.AddEdge(ta, tb, int(ic.H.V), 0, 0)
					inter.AddEdge(tb, ta, int(ic.H.V), 1, 0)
				} else {
					bkwds := true
					if dot < 0 {
						bkwds = !bkwds
					}
					if t == SurfaceDiff && !opA {
						bkwds = !bkwds
					}
					if t == SurfaceInter {
						bkwds = !bkwds
					}
					ta := geom.Vector{X: tap.U, Y: tap.V}
					tb := geom.Vector{X: tbp.U, Y: tbp.V}
					if bkwds {
						inter.AddEdge(tb, ta, int(ic.H.V), 1, 0)
					} else {
						inter.AddEdge(ta, tb, int(ic.H.V), 0, 0)
					}
				}
			}
			prev = cur
			prevPuv = curPuv
		}
	}

	// Step 5 (C++ line 596-618): build the list of "choosing points"
	// — junctions where more than 2 edges meet. Edges meeting at a
	// non-choosing point must either all be kept or all be discarded
	// (otherwise the trim polygon would be open).
	choosing := []geom.Vector{}
	incrementTag := func(p geom.Vector) {
		const tol = 1e-9
		for i := range choosing {
			if p.DistanceTo(choosing[i]) < tol {
				return
			}
		}
		choosing = append(choosing, p)
	}
	for i := range orig.Edges {
		incrementTag(orig.Edges[i].A)
		incrementTag(orig.Edges[i].B)
	}
	for i := range inter.Edges {
		incrementTag(inter.Edges[i].A)
		incrementTag(inter.Edges[i].B)
	}
	// (choosing doesn't need an explicit "tag 2" pass because
	// Go's struct-less slice is intrinsically set-like; we filter
	// at the chain-finding step using the duplicates.)

	// Step 6 (C++ line 623-661): walk orig chains, classify, keep.
	final := &SEdgeList{}
	for len(orig.Edges) > 0 {
		chain := &SEdgeList{}
		findChainAvoiding(orig, chain, &choosing)
		if len(chain.Edges) == 0 {
			break
		}
		midIdx := len(chain.Edges) / 2
		if midIdx >= len(chain.Edges) {
			midIdx = len(chain.Edges) - 1
		}
		se := &chain.Edges[midIdx]
		auv := geom.Point2d{U: se.A.X, V: se.A.Y}
		buv := geom.Point2d{U: se.B.X, V: se.B.Y}
		var surfN, enin, enout geom.Vector
		_, enin, enout = ret.edgeNormalsWithinSurface(auv, buv, into, sha, shb, se.AuxA, &surfN)
		pt := ret.PointAtUv(geom.Point2d{U: (auv.U + buv.U) / 2, V: (auv.V + buv.V) / 2})
		var indirShell, outdirShell SShellClass = ShellOutside, ShellOutside
		agnst.classifyEdge(&indirShell, &outdirShell,
			ret.PointAtUv(auv), ret.PointAtUv(buv),
			pt, enin, enout, surfN)
		if keepEdge(t, opA,
			indirShell, outdirShell,
			ShellInside, ShellOutside) {
			for _, e := range chain.Edges {
				final.AddEdge(e.A, e.B, e.AuxA, e.AuxB, 0)
			}
		}
		chain.Edges = nil
	}

	// Step 7 (C++ line 663-720): walk inter chains, classify, keep.
	for len(inter.Edges) > 0 {
		chain := &SEdgeList{}
		findChainAvoiding(inter, chain, &choosing)
		if len(chain.Edges) == 0 {
			break
		}
		midIdx := len(chain.Edges) / 2
		if midIdx >= len(chain.Edges) {
			midIdx = len(chain.Edges) - 1
		}
		se := &chain.Edges[midIdx]
		auv := geom.Point2d{U: se.A.X, V: se.A.Y}
		buv := geom.Point2d{U: se.B.X, V: se.B.Y}
		var surfN, enin, enout geom.Vector
		_, enin, enout = ret.edgeNormalsWithinSurface(auv, buv, into, sha, shb, se.AuxA, &surfN)
		pt := ret.PointAtUv(geom.Point2d{U: (auv.U + buv.U) / 2, V: (auv.V + buv.V) / 2})
		var indirShell, outdirShell SShellClass = ShellOutside, ShellOutside
		var indirOrig, outdirOrig SShellClass = ShellInside, ShellOutside
		var cThis BspUvClass = BspUvOutside
		if origBsp != nil {
			cThis = origBsp.ClassifyEdge(auv, buv)
		}
		if cThis == BspUvEdgeParallel {
			chain.Edges = nil
			continue
		}
		tagByClassifiedEdge(cThis, &indirOrig, &outdirOrig)
		agnst.classifyEdge(&indirShell, &outdirShell,
			ret.PointAtUv(auv), ret.PointAtUv(buv),
			pt, enin, enout, surfN)
		if keepEdge(t, opA,
			indirShell, outdirShell,
			indirOrig, outdirOrig) {
			for _, e := range chain.Edges {
				final.AddEdge(e.A, e.B, e.AuxA, e.AuxB, 0)
			}
		}
		chain.Edges = nil
	}

	// Step 8 (C++ line 723-727): cull duplicate / anti-parallel edges.
	final.CullExtraneousEdges(true)

	// Step 9 (C++ line 729-744): assemble the trim polygon from the
	// kept edges; mark booleanFailed in `into` if it fails to close.
	ret.trimFromEdgeList(final, true)
	var poly SPolygon
	final.lClearTags()
	if !final.AssemblePolygon(&poly, nil, true) {
		into.BooleanFailed = true
	}

	return ret
}

// lClearTags is a small helper to reset the Tag field on every edge
// in el (used after the inter/orig chain extraction above).
func (el *SEdgeList) lClearTags() {
	for i := range el.Edges {
		el.Edges[i].Tag = 0
	}
}

// copySurfacesTrimAgainstAccurate replaces CopySurfacesTrimAgainst
// with the proper per-surface MakeCopyTrimAgainst pipeline. For each
// surface in `sha`, it produces a trimmed copy whose boundary
// includes both sha's (split) trim curves and the new intersection
// curves computed against `shb`. The resulting surfaces are appended
// to `into`.
func copySurfacesTrimAgainstAccurate(sha, shb, into *SShell, t SurfaceCombineAs) {
	if sha == nil || shb == nil || into == nil {
		return
	}
	for i := range sha.Surface {
		srf := &sha.Surface[i]
		trimmed := srf.makeCopyTrimAgainst(sha, sha, shb, into, t, i)
		trimmed.NewH = core.HSSurface{V: uint32(len(into.Surface) + 1)}
		trimmed.H = trimmed.NewH
		into.Surface = append(into.Surface, trimmed)
	}
}
