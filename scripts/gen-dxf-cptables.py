#!/usr/bin/env python3
"""Generate pkg/dxf/dxfread's code page tables from libdxfrw's headers
(extlib/libdxfrw/intern/drw_cptable*.h in a SolveSpace source tree): the single-byte
pages as Go source (cptables.go), the double-byte ones (932, 936, 949,
950) as a gzipped blob (cpdbcs.bin.gz) of, for each page in that order,
a uint32 count and that many lead-table entries, then a uint32 count and
that many (code, unicode) uint32 pairs, all little-endian.

Usage: scripts/gen-dxf-cptables.py
"""
import gzip
import os
import re
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "solvespace", "extlib", "libdxfrw", "intern")
OUT = os.path.join(ROOT, "pkg", "dxf", "dxfread")


def array(text, name):
    m = re.search(r"static const int " + re.escape(name) + r"(\[[^\]]*\])*\s*=\s*\{", text)
    assert m, name
    depth = 1
    i = m.end()
    start = i
    while depth:
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
        i += 1
    body = re.sub(r"//[^\n]*", "", text[start:i - 1])
    return [int(v, 0) for v in re.findall(r"-?0[xX][0-9a-fA-F]+|-?\d+", body)]


single = open(os.path.join(SRC, "drw_cptables.h")).read()
pages = ["874", "1250", "1251", "1252", "1253", "1254", "1255", "1256", "1257", "1258"]
lines = [
    "// Code generated by scripts/gen-dxf-cptables.py from libdxfrw's",
    "// drw_cptables.h; DO NOT EDIT.",
    "",
    "package dxfread",
    "",
    "// singleByteTables are the Windows code pages' characters 0x80-0xFF",
    "// (C++ DRW_Table874 and so on).",
    "var singleByteTables = map[string]*[128]int32{",
]
for p in pages:
    t = array(single, "DRW_Table" + p)
    assert len(t) == 128, (p, len(t))
    lines.append('\t"ANSI_%s": {' % p)
    for k in range(0, 128, 8):
        lines.append("\t\t" + ", ".join("0x%04X" % v for v in t[k:k + 8]) + ",")
    lines.append("\t},")
lines.append("}")
open(os.path.join(OUT, "cptables.go"), "w").write("\n".join(lines) + "\n")

blob = b""
for p in ["932", "936", "949", "950"]:
    text = open(os.path.join(SRC, "drw_cptable%s.h" % p)).read()
    lead = array(text, "DRW_LeadTable" + p)
    double = array(text, "DRW_DoubleTable" + p)
    assert len(double) % 2 == 0
    blob += struct.pack("<I", len(lead)) + b"".join(struct.pack("<I", v) for v in lead)
    blob += struct.pack("<I", len(double) // 2) + b"".join(struct.pack("<I", v) for v in double)
open(os.path.join(OUT, "cpdbcs.bin.gz"), "wb").write(gzip.compress(blob, mtime=0))
