#!/usr/bin/env python3
"""Write pkg/res/unifont_widths.go: the ranges of code points whose
Unifont glyph is two cells (16 pixels) wide, read from the bundled
pkg/res/data/fonts/unifont.hex.gz. BitmapFont.Width answers from it, so
that laying text out doesn't inflate the font; TestUnifontWidths checks
the table against the font.

Usage: scripts/gen-unifont-widths.py
"""
import gzip
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
FONT = os.path.join(ROOT, 'pkg', 'res', 'data', 'fonts', 'unifont.hex.gz')
OUT = os.path.join(ROOT, 'pkg', 'res', 'unifont_widths.go')

ranges = []
with gzip.open(FONT, 'rt', encoding='ascii') as f:
    for line in f:
        cp, bits = line.strip().split(':')
        if len(bits) != 64:
            continue
        c = int(cp, 16)
        if ranges and ranges[-1][1] == c - 1:
            ranges[-1][1] = c
        else:
            ranges.append([c, c])

with open(OUT, 'w', encoding='ascii') as out:
    out.write('// Code generated by scripts/gen-unifont-widths.py; DO NOT EDIT.\n\n')
    out.write('package res\n\n')
    out.write('// unifontWide are the code points, as sorted inclusive ranges, whose\n')
    out.write('// Unifont glyph is two cells wide; every other glyph, U+FFFD that\n')
    out.write('// stands for a missing one included, is one.\n')
    out.write('var unifontWide = [...]struct{ lo, hi rune }{\n')
    for lo, hi in ranges:
        out.write('\t{0x%04X, 0x%04X},\n' % (lo, hi))
    out.write('}\n')
