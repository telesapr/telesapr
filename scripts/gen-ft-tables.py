#!/usr/bin/env python3
"""Generate pkg/ttf/fttables.go: the constant tables pkg/ttf ports from
FreeType 2.14.3 -- the CFF driver's predefined charsets and encodings
(src/cff/cffload.c) and the psnames module's glyph names, SID strings,
Type 1 encodings and Adobe Glyph List trie (src/psnames/pstables.h).

Usage: gen-ft-tables.py <freetype-2.14.3 source dir> > pkg/ttf/fttables.go
"""
import re
import sys

src = sys.argv[1]


def c_array(text, name):
    """The initializer of the C array `name` in text, as a list of ints."""
    m = re.search(r"\b" + re.escape(name) + r"\s*\[[^\]]*\]\s*(?:#ifdef\s+\w+\s*)?=\s*\{(.*?)\}"
                  r"\s*(?:#endif[^\n]*\s*)?;", text, re.S)
    if not m:
        raise SystemExit("array %s not found" % name)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    vals = []
    for tok in re.finditer(r"'(\\.|[^'])'|(0x[0-9A-Fa-f]+|-?\d+)[UuLl]*", body):
        if tok.group(1) is not None:
            c = tok.group(1)
            if c.startswith("\\"):
                c = {"\\0": "\0", "\\'": "'", "\\\\": "\\"}[c]
            vals.append(ord(c))
        else:
            vals.append(int(tok.group(2), 0))
    return vals


def go_ints(name, typ, vals, per_line=12):
    out = ["var %s = [...]%s{" % (name, typ)]
    for i in range(0, len(vals), per_line):
        out.append("\t" + ", ".join(str(v) for v in vals[i:i + per_line]) + ",")
    out.append("}")
    return "\n".join(out)


def go_bytes(name, vals):
    def esc(v):
        if 32 <= v < 127 and chr(v) not in '"\\':
            return chr(v)
        return "\\x%02x" % v

    lines = ['const %s = "" +' % name]
    line = ""
    for v in vals:
        line += esc(v)
        if len(line) >= 90:
            lines.append('\t"%s" +' % line)
            line = ""
    if line:
        lines.append('\t"%s" +' % line)
    lines[-1] = lines[-1][:-2]
    return "\n".join(lines)


cffload = open(src + "/src/cff/cffload.c").read()
pstables = open(src + "/src/psnames/pstables.h").read()

print("// Code generated by scripts/gen-ft-tables.py from FreeType 2.14.3; DO NOT EDIT.")
print()
print("package ttf")
print()
for c_name, go_name in [("cff_isoadobe_charset", "cffISOAdobeCharset"),
                        ("cff_expert_charset", "cffExpertCharset"),
                        ("cff_expertsubset_charset", "cffExpertSubsetCharset"),
                        ("cff_standard_encoding", "cffStandardEncoding"),
                        ("cff_expert_encoding", "cffExpertEncoding")]:
    print("// %s is cffload.c's %s." % (go_name, c_name))
    print(go_ints(go_name, "uint16", c_array(cffload, c_name)))
    print()

print("// ftStandardGlyphNames is pstables.h's ft_standard_glyph_names.")
print(go_bytes("ftStandardGlyphNames", c_array(pstables, "ft_standard_glyph_names")))
print()
for c_name, go_name, typ in [("ft_mac_names", "ftMacNames", "int16"),
                             ("ft_sid_names", "ftSIDNames", "int16"),
                             ("t1_standard_encoding", "t1StandardEncoding", "uint16"),
                             ("t1_expert_encoding", "t1ExpertEncoding", "uint16")]:
    print("// %s is pstables.h's %s." % (go_name, c_name))
    print(go_ints(go_name, typ, c_array(pstables, c_name)))
    print()
print("// ftAdobeGlyphList is pstables.h's ft_adobe_glyph_list.")
print(go_bytes("ftAdobeGlyphList", c_array(pstables, "ft_adobe_glyph_list")))
