#!/usr/bin/env python3
"""Write pkg/libm/tables.go: the lookup tables of glibc's IBM
Accurate Mathematical Library functions, read from the static libm
(libm-2.44.a) that C++ SolveSpace's glibc ships, so no value is
transcribed by hand.

Usage: scripts/gen-libm-tables.py [/usr/lib/libm-2.44.a]
Needs pyelftools and binutils' ar.
"""
import io
import os
import struct
import subprocess
import sys
import tempfile

from elftools.elf.elffile import ELFFile

LIBM = sys.argv[1] if len(sys.argv) > 1 else '/usr/lib/libm-2.44.a'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'pkg', 'libm', 'tables.go')

# (Go name, object file, symbol, element type, comment)
TABLES = [
    ('sincostab', 'sincostab.o', '__sincostab', 'f64',
     'sincostab is __sincostab (sincostab.c): sin, sin tail, cos, cos tail at k/128.'),
    ('xfg', 's_tan-fma.o', 'xfg.12', 'f64',
     'xfg is the table of s_tan.c (utan.tbl), xfg[i][0..3] at 4*i.'),
    ('cij', 's_atan-fma.o', 'cij', 'f64',
     'cij is the table of s_atan.c and e_atan2.c (uatan.tbl), cij[i][0..6] at 7*i.'),
    ('asncs', 'e_asin-fma.o', 'asncs', 'f64',
     'asncs is the table of e_asin.c (asincos.tbl).'),
    ('inroot', 'e_asin-fma.o', 'inroot', 'f64',
     'inroot is the table of e_asin.c (root.tbl).'),
    ('powtwo', 'e_asin-fma.o', 'powtwo', 'f64',
     'powtwo is the table of e_asin.c (powtwo.tbl).'),
    ('twoOverPi', 'e_rem_pio2.o', 'two_over_pi', 'i32',
     'twoOverPi is two_over_pi of e_rem_pio2.c: 2/pi in 24-bit chunks.'),
]


def symbol_bytes(path, name):
    f = ELFFile(open(path, 'rb'))
    for s in f.get_section_by_name('.symtab').iter_symbols():
        if s.name == name:
            data = f.get_section(s['st_shndx']).data()
            return data[s['st_value']:s['st_value'] + s['st_size']]
    raise KeyError(name)


def main():
    tmp = tempfile.mkdtemp()
    objs = sorted({t[1] for t in TABLES})
    subprocess.check_call(['ar', 'x', LIBM] + objs, cwd=tmp)
    out = io.StringIO()
    out.write('// Code generated by scripts/gen-libm-tables.py from %s; DO NOT EDIT.\n\n' % os.path.basename(LIBM))
    out.write('package libm\n\n')
    for name, obj, sym, typ, comment in TABLES:
        b = symbol_bytes(os.path.join(tmp, obj), sym)
        out.write('// %s\n' % comment)
        if typ == 'f64':
            vals = struct.unpack('<%dQ' % (len(b) // 8), b)
            out.write('var %s = f64s([]uint64{\n' % name)
            for i in range(0, len(vals), 4):
                out.write('\t' + ' '.join('0x%016x,' % v for v in vals[i:i + 4]) + '\n')
            out.write('})\n\n')
        else:
            vals = struct.unpack('<%di' % (len(b) // 4), b)
            out.write('var %s = []int32{\n' % name)
            for i in range(0, len(vals), 6):
                out.write('\t' + ' '.join('0x%06X,' % v for v in vals[i:i + 6]) + '\n')
            out.write('}\n\n')
    with open(OUT, 'w') as f:
        f.write(out.getvalue().rstrip('\n') + '\n')


if __name__ == '__main__':
    main()
